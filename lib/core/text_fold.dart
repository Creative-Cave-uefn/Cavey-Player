/// Нижний регистр, без диакритики, схлопнутые пробелы
String foldText(String s) {
  final b = StringBuffer();
  for (final r in s.toLowerCase().runes) {
    if (r >= 0x300 && r <= 0x36F) continue; // комбинируемые диакритические знаки
    b.write(_map[r] ?? String.fromCharCode(r));
  }
  return b.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
}

/// То же, но ещё и без знаков препинания и пометок «(Remastered 2011)»: для склейки альбомов
String foldAlbumTitle(String s) {
  var t = s.toLowerCase();
  t = t.replaceAll(RegExp(r'[\(\[][^\)\]]*remaster[^\)\]]*[\)\]]'), ' ');
  t = t.replaceAll(RegExp(r'\s+-\s+(?:\d{4}\s+)?remaster(?:ed)?(?:\s+\d{4})?\s*$'), ' ');
  return foldText(t).replaceAll(RegExp(r'[^\p{L}\p{N}]+', unicode: true), ' ').trim();
}
